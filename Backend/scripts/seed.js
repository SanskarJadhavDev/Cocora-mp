const seedDatabase = async () => {
  const isConnected = await connectDB();
  if (!isConnected) {
    console.error('Seed script error: Unable to connect to database');
    process.exit(1);
  }

  let insertedCount = 0;
  let updatedCount = 0;
  let unchangedCount = 0;

  try {
    for (const item of catalogue) {
      const canonicalSlug = slugify(item.name);
      const existing = await Product.findOne({
        $or: [{ slug: canonicalSlug }, { name: item.name }]
      });

      if (!existing) {
        await Product.create({
          ...item,
          slug: canonicalSlug
        });
        insertedCount++;
      } else {
        let changed = false;

        const fieldsToSync = [
          'description',
          'category',
          'chocolateType',
          'cocoaPercentage',
          'sweetnessLevel',
          'image',
          'price',
          'isFeatured'
        ];

        for (const field of fieldsToSync) {
          const existingVal = existing[field] === null || existing[field] === undefined ? '' : existing[field];
          const targetVal = item[field] === null || item[field] === undefined ? '' : item[field];
          if (existingVal !== targetVal) {
            existing[field] = item[field];
            changed = true;
          }
        }

        const arrayFields = [
          'flavourNotes',
          'ingredients',
          'allergens',
          'dietaryTags',
          'suitableOccasions',
          'suitableRecipients'
        ];

        for (const field of arrayFields) {
          const currentArr = Array.from(existing[field] || []);
          const targetArr = Array.from(item[field] || []);
          if (JSON.stringify(currentArr) !== JSON.stringify(targetArr)) {
            existing[field] = targetArr;
            changed = true;
          }
        }

        if (changed) {
          await existing.save();
          updatedCount++;
        } else {
          unchangedCount++;
        }
      }
    }

    console.log('Catalogue Seeding Completed Successfully');
    console.log(`Summary: Total Target=${catalogue.length} | Inserted=${insertedCount} | Updated=${updatedCount} | Unchanged=${unchangedCount}`);

    const counts = await Product.aggregate([
      { $group: { _id: '$category', count: { $sum: 1 } } }
    ]);
    console.log('Category Distribution in Database:');
    counts.forEach((c) => {
      console.log(`- ${c._id}: ${c.count}`);
    });

    await mongoose.disconnect();
    return {
      total: catalogue.length,
      inserted: insertedCount,
      updated: updatedCount,
      unchanged: unchangedCount
    };
  } catch (error) {
    console.error('Seeding process failed:', error.message);
    await mongoose.disconnect();
    process.exit(1);
  }
};

if (require.main === module) {
  seedDatabase();
}

